class SortFilter :
    Filter.Select<String>(
        "Ordenar por",
        SORT_OPTIONS.map { it.first }.toTypedArray(),
    ) {
    fun toValue(): String = SORT_OPTIONS[state].second

    companion object {
        private val SORT_OPTIONS = listOf(
            Pair("Más recientes", "date"),
            Pair("Más comentados / Populares", "comment_count"),
            Pair("Título", "title"),
            Pair("Aleatorio", "rand"),
        )
    }
}

